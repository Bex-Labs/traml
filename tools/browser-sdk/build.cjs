// Reproducible, offline-at-runtime browser SDK. Run npm ci here before rebuilding.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const esbuild=require('esbuild');
async function main(){
 const sdk=require('@supabase/supabase-js/package.json'),tool=require('esbuild/package.json');
 const dir=path.resolve(__dirname,'../../js/vendor'),stem='supabase-js-'+sdk.version;fs.mkdirSync(dir,{recursive:true});
 const file=path.join(dir,stem+'.js');
 const result=await esbuild.build({absWorkingDir:__dirname,stdin:{contents:'export { createClient } from "@supabase/supabase-js";',resolveDir:__dirname,sourcefile:'<browser-sdk-entry>'},outfile:file,bundle:true,platform:'browser',format:'esm',target:['es2022'],supported:{'template-literal':false},minify:true,legalComments:'eof',metafile:true,logLevel:'silent',banner:{js:'// Supabase JS '+sdk.version+'; generated by tools/browser-sdk/build.cjs. See '+stem+'.LICENSE.txt.'}});
 const external=Object.values(result.metafile.outputs).flatMap(o=>o.imports).filter(i=>i.external);if(external.length)throw Error('Bundle retains external imports: '+external.map(i=>i.path).join(', '));
 const packages=new Map();
 for(const input of Object.keys(result.metafile.inputs)){
  if(input.startsWith('<'))continue;
  let folder=path.dirname(path.resolve(__dirname,input));
  while(folder!==path.dirname(folder)){
   const metadata=path.join(folder,'package.json');
   if(fs.existsSync(metadata)){const p=JSON.parse(fs.readFileSync(metadata,'utf8'));if(p.name&&p.version){packages.set(p.name,{...p,folder});break;}}
   folder=path.dirname(folder);
  }
 }
 const ordered=[...packages.values()].sort((a,b)=>a.name.localeCompare(b.name));const licenses=[];
 for(const p of ordered){
  const name=fs.readdirSync(p.folder).find(n=>/^licen[sc]e(?:\.(?:md|txt))?$/i.test(n));
  if(!name)throw Error('License file missing for '+p.name);
  licenses.push(p.name+' '+p.version+' ('+p.license+')\n'+fs.readFileSync(path.join(p.folder,name),'utf8'));
 }
 fs.writeFileSync(path.join(dir,stem+'.LICENSE.txt'),licenses.join('\n\n----------------------------------------\n\n').replace(/\r\n?/g,'\n')+'\n');
 fs.writeFileSync(path.join(dir,stem+'.manifest.json'),JSON.stringify({sdk:sdk.name,version:sdk.version,builder:'esbuild '+tool.version,format:'esm',external_imports:[],sha256:crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'),packages:ordered.map(p=>({name:p.name,version:p.version,license:p.license}))},null,2)+'\n');
 console.log('Built '+stem+'.js with '+ordered.length+' attributed packages and no external imports.');
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
